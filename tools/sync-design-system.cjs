const fs = require('node:fs'),
  path = require('node:path');
const root = path.resolve(__dirname, '..'),
  spec = JSON.parse(fs.readFileSync(path.join(root, 'design/jingyu-components.json'), 'utf8'));
const check = process.argv.includes('--check');
const lines = [];
lines.push(
  `  --jy-control-size: ${spec.size.control}px;`,
  `  --jy-control-touch: ${spec.size.touch}px;`,
  `  --jy-icon-size: ${spec.size.icon}px;`,
);
for (const [key, value] of Object.entries(spec.size))
  lines.push(
    `  --jy-${key.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase())}: ${key === 'bubbleMax' ? value * 100 + '%' : value + 'px'};`,
  );
for (const [key, value] of Object.entries(spec.space))
  lines.push(`  --jy-space-${key}: ${value}px;`);
for (const [key, value] of Object.entries(spec.radius))
  lines.push(`  --jy-radius-${key}: ${value}px;`);
for (const [key, value] of Object.entries(spec.type))
  lines.push(`  --jy-type-${key}: ${key === 'line' ? value : value + 'px'};`);
for (const [key, value] of Object.entries(spec.motion))
  lines.push(`  --jy-motion-${key}: ${key === 'ease' ? value : value + 'ms'};`);
for (const [key, value] of Object.entries(spec.layers))
  lines.push(`  --jy-layer-${key}: ${value};`);
const palette = (theme) =>
  Object.entries(spec[theme])
    .map(([k, v]) => `  --jy-color-${k}: ${v};`)
    .join('\n');
const token = (native) =>
  `/* Generated by tools/sync-design-system.cjs. Edit design/jingyu-components.json. */\n${native ? 'page, :host, .native-surface, .native-theme, .theme-light' : ':root'} {\n${lines.join('\n')}\n${palette('light')}\n}\n${native ? '.theme-dark, .native-surface.theme-dark' : "html[data-appearance='dark'], [data-theme='dark']"} {\n${palette('dark')}\n}\n`;
const outputs = {
  'dist/shared/design-tokens.css': token(false),
  'miniprogram/styles/design-tokens.wxss': token(true),
  'miniprogram/services/design-tokens.js': `// Generated from design/jingyu-components.json.\nmodule.exports = ${JSON.stringify(
    {
      ...spec,
      variables: Object.fromEntries(
        lines.map((line) => {
          const match = line.match(/^\s*(--[^:]+): (.*);$/);
          return [match[1], match[2]];
        }),
      ),
    },
    null,
    2,
  )};\n`,
};
for (const [name, body] of Object.entries(outputs)) {
  const p = path.join(root, name);
  if (check) {
    if (!fs.existsSync(p) || fs.readFileSync(p, 'utf8').replace(/\r\n/g, '\n') !== body)
      throw Error('Stale design system: ' + name);
  } else fs.writeFileSync(p, body);
}
console.log(
  check
    ? 'Shared web/native design tokens are current.'
    : 'Generated identical logical dimensions, palettes and motion tokens for web/native.',
);
