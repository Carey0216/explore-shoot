const n = (v) => Number(v.toFixed(3));
function markup(p) {
  const v = p.p;
  switch (p.t) {
    case 'line':
      return `<line x1="${v[0]}" y1="${v[1]}" x2="${v[2]}" y2="${v[3]}"/>`;
    case 'poly':
      return `<polyline points="${v.reduce((a, x, i) => a + (i % 2 ? ',' : ' ') + x, '').trim()}"/>`;
    case 'circle':
      return `<circle cx="${v[0]}" cy="${v[1]}" r="${v[2]}"/>`;
    case 'rect':
      return `<rect x="${v[0]}" y="${v[1]}" width="${v[2]}" height="${v[3]}" rx="${v[4] || 0}"/>`;
    case 'bezier':
      return `<path d="M${v[0]} ${v[1]}C${v.slice(2).join(' ')}"/>`;
    case 'arc': {
      const [x, y, w, h, start, sweep] = v;
      if (Math.abs(sweep) === 360)
        return `<ellipse cx="${x + w / 2}" cy="${y + h / 2}" rx="${w / 2}" ry="${h / 2}"/>`;
      const p = (a) => [
        n(x + w / 2 + (w / 2) * Math.cos((a * Math.PI) / 180)),
        n(y + h / 2 + (h / 2) * Math.sin((a * Math.PI) / 180)),
      ];
      return `<path d="M${p(start).join(' ')}A${w / 2} ${h / 2} 0 ${Math.abs(sweep) > 180 ? 1 : 0} ${sweep > 0 ? 1 : 0} ${p(start + sweep).join(' ')}"/>`;
    }
  }
}
